# Automatic Root and POS detector
def detect_root_and_pos(mn):
    # Verb patterns
    # e.g. ав(ах), буу(х), ажилла(х), яри(х), ярь, амра(х), амар
    if '(ах)' in mn or '(эх)' in mn or '(их)' in mn or '(ох)' in mn or '(өх)' in mn or '(х)' in mn:
        base = re.sub(r'\([^\)]+\)', '', mn).strip()
        # If phrase
        if ' ' in base:
            parts = base.split()
            last_verb = parts[-1]
            return f"{last_verb}-", "動詞句"
        return f"{base}-", "動詞"
    elif '(н)' in mn:
        base = mn.replace('(н)', '').strip()
        return f"{base}(н)", "名詞（隠れн）"
    elif '(г)' in mn:
        base = mn.replace('(г)', '').strip()
        return f"{base}(г)", "名詞（隠れг）"
    elif ' гараг' in mn or ' өдөр' in mn:
        return "", "時間・暦名詞"
    elif mn.endswith('тай') or mn.endswith('тэй') or mn.endswith('той'):
        return "", "形容詞"
    elif mn.endswith('хан') or mn.endswith('хэн') or mn.endswith('хон'):
        return "", "形容詞"
    elif ' ' in mn:
        return "", "連語・句"
    return "", "名詞"

